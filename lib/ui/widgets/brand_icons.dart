import 'package:flutter/widgets.dart';

/// LinkedIn, GitHub and LeetCode marks, drawn from Simple Icons path data
/// (CC0, 24×24 grid) so no icon package or font is needed.
enum Brand { linkedIn, gitHub, leetCode }

/// Paints a [Brand] mark in the ambient [IconTheme] colour, like [Icon].
class BrandIcon extends StatelessWidget {
  const BrandIcon(this.brand, {super.key, this.size});

  final Brand brand;
  final double? size;

  @override
  Widget build(BuildContext context) {
    final theme = IconTheme.of(context);
    final size = this.size ?? theme.size ?? 24;
    return ExcludeSemantics(
      child: SizedBox.square(
        dimension: size,
        child: CustomPaint(
          painter: _BrandPainter(brand, theme.color ?? const Color(0xFF000000)),
        ),
      ),
    );
  }
}

class _BrandPainter extends CustomPainter {
  _BrandPainter(this.brand, this.color);

  final Brand brand;
  final Color color;

  static final _paths = {
    Brand.linkedIn: _linkedin(),
    Brand.gitHub: _github(),
    Brand.leetCode: _leetcode(),
  };

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 24, size.height / 24);
    canvas.drawPath(_paths[brand]!, Paint()..color = color);
  }

  @override
  bool shouldRepaint(_BrandPainter old) =>
      old.brand != brand || old.color != color;
}

